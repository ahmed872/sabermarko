// CI only: take the vendor's license PRIVATE key from the GitHub Actions secret SBM_LICENSE_PRIVATE_KEY
// (passed in the environment, never on the command line, never printed), and
//   1. write it to a private temp file for tools/license/issue.mjs  (--key-out <file>, optional)
//   2. write the matching PUBLIC key into src/main/license/public-key.ts, so the build always embeds the
//      public half of exactly the key that issues the activation codes (the two can never drift apart).
//
//   node tools/license/use-secret-key.mjs [--key-out $RUNNER_TEMP/k.pem] [--optional]
// --optional: no secret -> keep the key already in the repository and exit 0 (manual test builds).
import { createPrivateKey, createPublicKey } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { PUBLIC_KEY_TS, fingerprint, parseArgs } from './common.mjs';

const args = parseArgs(process.argv.slice(2));
const raw = (process.env.SBM_LICENSE_PRIVATE_KEY || '').trim();
if (!raw) {
  if (args.optional) { console.log('SBM_LICENSE_PRIVATE_KEY secret not set: keeping the license key that is in the repository.'); process.exit(0); }
  console.error('لم يتم ضبط السر SBM_LICENSE_PRIVATE_KEY في إعدادات المستودع (Settings → Secrets and variables → Actions).\nThe repository secret SBM_LICENSE_PRIVATE_KEY is not set.');
  process.exit(2);
}
let priv;
try {
  priv = createPrivateKey({ key: raw.replace(/\\n/g, '\n'), format: 'pem' });
} catch {
  console.error('السر SBM_LICENSE_PRIVATE_KEY ليس مفتاحًا خاصًا صحيحًا. الصق محتوى ملف sabermarko-private-key.pem كاملًا (من BEGIN إلى END).\nSBM_LICENSE_PRIVATE_KEY is not a valid PEM private key.');
  process.exit(2);
}
if (priv.asymmetricKeyType !== 'ed25519') { console.error(`SBM_LICENSE_PRIVATE_KEY must be an Ed25519 key (got ${priv.asymmetricKeyType}).`); process.exit(2); }
const pub = createPublicKey(priv).export({ type: 'spki', format: 'pem' }).toString().trim();
writeFileSync(PUBLIC_KEY_TS, `// Vendor license verification key (PUBLIC — safe to commit). Generated by tools/license/keygen.mjs\n// Fingerprint: ${fingerprint(pub)}\nexport const LICENSE_PUBLIC_KEY = \`${pub}\`;\n`);
if (typeof args['key-out'] === 'string') writeFileSync(args['key-out'], priv.export({ type: 'pkcs8', format: 'pem' }), { mode: 0o600 });
console.log(`license key from the repository secret — fingerprint ${fingerprint(pub)}`);
